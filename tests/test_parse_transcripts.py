def test_find_agent_files_discovers_top_level_and_nested_workflow_agents(tmp_path):
    session_dir = tmp_path / "sess5"
    (session_dir / "subagents").mkdir(parents=True)
    (session_dir / "subagents" / "agent-a111.jsonl").write_text("{}\n")
    (session_dir / "subagents" / "agent-a111.meta.json").write_text(
        json.dumps({"agentType": "general-purpose", "toolUseId": "tu_agent"})
    )
    wf_dir = session_dir / "subagents" / "workflows" / "wf_abc"
    wf_dir.mkdir(parents=True)
    (wf_dir / "agent-a222.jsonl").write_text("{}\n")
    (wf_dir / "agent-a222.meta.json").write_text(json.dumps({"agentType": "workflow-subagent"}))

    files = find_agent_files(session_dir)
    assert set(files.keys()) == {"a111", "a222"}
    assert files["a111"]["workflow_run_id"] is None
    assert files["a222"]["workflow_run_id"] == "wf_abc"


def test_link_agent_ids_via_meta_fallback(tmp_path):
    session_dir = tmp_path / "sess6"
    (session_dir / "subagents").mkdir(parents=True)
    (session_dir / "subagents" / "agent-aFB.jsonl").write_text("{}\n")
    (session_dir / "subagents" / "agent-aFB.meta.json").write_text(
        json.dumps({"agentType": "general-purpose", "toolUseId": "tu_no_result"})
    )
    lines = [
        user_text("go"),
        assistant_block(
            {
                "type": "tool_use",
                "id": "tu_no_result",
                "name": "Agent",
                "input": {"description": "d", "subagent_type": "general-purpose", "prompt": "p"},
            }
        ),
        # no matching tool_result at all -> must fall back to meta.json scan
    ]
    parsed = parse_transcript("sess6", lines)
    agent_files = find_agent_files(session_dir)
    link_agent_ids_via_meta(parsed, agent_files)
    assert {"tool_use_id": "tu_no_result", "agent_id": "aFB"} in parsed.agent_links


