def line(**kw):
    base = {"timestamp": "2026-01-01T00:00:00.000Z", "gitBranch": "main", "cwd": "/Users/drmaciver/Projects/autoroad"}
    base.update(kw)
    return base


def user_text(text, ts="2026-01-01T00:00:00.000Z"):
    return line(type="user", timestamp=ts, message={"role": "user", "content": text})


def assistant_block(block, ts="2026-01-01T00:00:01.000Z"):
    return line(type="assistant", timestamp=ts, message={"role": "assistant", "content": [block]})


def tool_result_line(tool_use_id, content, tur=None, ts="2026-01-01T00:00:02.000Z"):
    d = line(
        type="user",
        timestamp=ts,
        message={
            "role": "user",
            "content": [{"type": "tool_result", "tool_use_id": tool_use_id, "content": content}],
        },
    )
    if tur is not None:
        d["toolUseResult"] = tur
    return d


def test_basic_turn_alternation_and_grouping():
    lines = [
        user_text("Hello, please list files."),
        assistant_block({"type": "thinking", "thinking": "let's look"}),
        assistant_block({"type": "text", "text": "I'll list them."}),
        assistant_block(
            {
                "type": "tool_use",
                "id": "tu1",
                "name": "Bash",
                "input": {"command": "ls -la", "description": "List files"},
            }
        ),
        tool_result_line("tu1", [{"type": "text", "text": "total 0\nfile.txt", "is_error": False}]),
        user_text("Thanks, now write a poem."),
        assistant_block({"type": "text", "text": "Roses are red."}),
    ]
    parsed = parse_transcript("sess1", lines)
    assert [t.role for t in parsed.turns] == ["user", "assistant", "user", "assistant"]

    assistant_turn = parsed.turns[1]
    kinds = [b["kind"] for b in assistant_turn.blocks]
    assert kinds == ["thinking", "text", "tool_use", "tool_result"]
    assert assistant_turn.blocks[2]["tool"] == "Bash"
    assert assistant_turn.blocks[2]["command"] == "ls -la"
    assert assistant_turn.blocks[3]["status"] == "ok"

    assert parsed.start == "2026-01-01T00:00:00.000Z"
    assert parsed.end == "2026-01-01T00:00:02.000Z"
    assert parsed.git_branch == "main"


