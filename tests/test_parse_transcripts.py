def test_read_jsonl_skips_blank_and_malformed_lines(tmp_path):
    p = tmp_path / "x.jsonl"
    p.write_text('{"a": 1}\n\n not json \n{"b": 2}\n')
    out = list(read_jsonl(p))
    assert out == [{"a": 1}, {"b": 2}]
